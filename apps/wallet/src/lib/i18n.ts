/** Pesan galat wallet untuk kode dari Rust; kode yang tidak dikenal memakai pesan umum. */
export function walletErrorText(t: Dict, code: string): string {
  const messages: Record<string, string> = t.walletErrors;
  return messages[code] ?? t.walletErrors.failed;
}
